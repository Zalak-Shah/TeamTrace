"""
============================================================
BorderShield AI - PAN Verification Module
============================================================
Features:
1. e-PAN PDF Digital Signature Validation (Tier 1):
   - Validates digital signatures issued by Income Tax Department / NSDL / UTIITSL.
2. Pluggable Issuer Lookup Interface (Tier 2):
   - Pluggable provider interface (e.g. NSDL / UTIITSL PAN Online Verification).
   - Mock implementation returns status "unverified: issuer check not connected".
   - Never fakes a pass.
3. Fallback Heuristics (Tier 3):
   - Checks PAN format: 5 letters, 4 digits, 1 letter (4th char = entity type: P=Person, C=Company, etc.).
============================================================
"""

import io
import re
from abc import ABC, abstractmethod
from typing import Any, Dict, Optional, Tuple

from modules.base import BaseDocumentVerifier, VerificationResult


PAN_REGEX = re.compile(r"\b([A-Z]{3})([CPHFATBLJG])([A-Z])([0-9]{4})([A-Z])\b", re.IGNORECASE)

PAN_ENTITY_TYPES = {
    "P": "Individual / Person",
    "C": "Company",
    "H": "Hindu Undivided Family (HUF)",
    "F": "Firm / Limited Liability Partnership",
    "A": "Association of Persons (AOP)",
    "T": "Trust",
    "B": "Body of Individuals (BOI)",
    "L": "Local Authority",
    "J": "Artificial Juridical Person",
    "G": "Government Agency",
}


class PanIssuerProvider(ABC):
    """
    Abstract pluggable interface for real-time PAN issuer database lookups.
    """

    @abstractmethod
    def verify_pan(self, pan_number: str, full_name: Optional[str] = None) -> Tuple[bool, str, Dict[str, Any]]:
        pass


class MockNsdlPanProvider(PanIssuerProvider):
    """
    Mock implementation when external government API credentials are not connected.
    STRICT RULE: Never fakes a pass; explicitly declares unverified.
    """

    def verify_pan(self, pan_number: str, full_name: Optional[str] = None) -> Tuple[bool, str, Dict[str, Any]]:
        return False, "unverified: issuer check not connected", {
            "provider": "NSDL / Protean eGov API",
            "connected": False,
            "note": "Requires production NSDL/UTIITSL or DigiLocker API credentials.",
        }


class PanVerifier(BaseDocumentVerifier):
    """
    Dedicated PAN Card Verification Module.
    """

    def __init__(self, provider: Optional[PanIssuerProvider] = None):
        self.provider = provider or MockNsdlPanProvider()

    def verify(
        self,
        file_bytes: bytes,
        filename: str,
        content_type: str,
        ocr_text: str,
        extracted_fields: Optional[Dict[str, Any]] = None,
    ) -> VerificationResult:
        reasons = []
        limitations = [
            "Physical PAN card images contain no verifiable digital signatures or MRZ.",
            "Visual examination cannot verify whether a PAN is active or deactivated without live NSDL/ITD portal connectivity.",
        ]
        checks = {}
        risk_score = 0
        extracted_fields = extracted_fields or {}

        # -------------------------------------------------------------
        # 1. e-PAN PDF Digital Signature Validation (Tier 1)
        # -------------------------------------------------------------
        if content_type == "application/pdf" or filename.lower().endswith(".pdf"):
            pdf_valid, pdf_msg, pdf_checks = self._verify_pdf_signature(file_bytes)
            checks["pdf_signature"] = pdf_checks
            if pdf_valid:
                reasons.append("Cryptographically valid e-PAN PDF digital certificate verified.")
                return VerificationResult(
                    document_type="pan",
                    verification_method="pdf_signature",
                    verification_tier=1,
                    status="verified",
                    risk_score=0,
                    reasons=reasons,
                    limitations=["Verifies document authenticity as generated by the issuing authority."],
                    checks=checks,
                )
            elif pdf_checks.get("signature_present") and not pdf_valid:
                reasons.append(f"CRITICAL: e-PAN PDF signature check failed: {pdf_msg}")
                return VerificationResult(
                    document_type="pan",
                    verification_method="pdf_signature",
                    verification_tier=1,
                    status="failed",
                    risk_score=100,
                    reasons=reasons,
                    limitations=[],
                    checks=checks,
                )

        # -------------------------------------------------------------
        # 2. Issuer Lookup Check (Tier 2 Pluggable Provider)
        # -------------------------------------------------------------
        doc_num = extracted_fields.get("document_number")
        pan_match = PAN_REGEX.search(ocr_text) if not doc_num else PAN_REGEX.search(doc_num)
        clean_pan = pan_match.group(0).upper() if pan_match else (doc_num.upper() if doc_num else None)

        if clean_pan:
            is_valid_issuer, issuer_msg, issuer_details = self.provider.verify_pan(
                clean_pan, extracted_fields.get("name_guess")
            )
            checks["issuer_lookup"] = issuer_details
            if is_valid_issuer:
                reasons.append(f"PAN record confirmed active by issuer database ({clean_pan}).")
                return VerificationResult(
                    document_type="pan",
                    verification_method="issuer_lookup",
                    verification_tier=2,
                    status="verified",
                    risk_score=5,
                    reasons=reasons,
                    limitations=[],
                    checks=checks,
                )
            else:
                reasons.append(f"Issuer Lookup: {issuer_msg}")

        # -------------------------------------------------------------
        # 3. Format & Heuristic Rules (Tier 3)
        # -------------------------------------------------------------
        checks["pan_format"] = {
            "pan_number": clean_pan,
            "detected": bool(pan_match),
        }

        if pan_match:
            entity_code = pan_match.group(2).upper()
            entity_desc = PAN_ENTITY_TYPES.get(entity_code, "Unknown entity")
            checks["pan_format"]["entity_type"] = entity_desc
            reasons.append(f"PAN format valid: '{clean_pan}' (Entity type: {entity_desc}).")

            # Check Income Tax Department headers
            has_itd = any(k in ocr_text.lower() for k in ["income tax department", "govt of india", "permanent account number"])
            if has_itd:
                reasons.append("Income Tax Department statutory header markings detected.")
                risk_score = 25
                status = "unverified"
            else:
                reasons.append("Income Tax Department header markers missing.")
                risk_score = 50
                status = "suspicious"
        else:
            reasons.append("No valid 10-character PAN format (AAAAA9999A) detected.")
            risk_score = 75
            status = "suspicious"

        return VerificationResult(
            document_type="pan",
            verification_method="forensics_only",
            verification_tier=3,
            status=status,
            risk_score=risk_score,
            reasons=reasons,
            limitations=limitations,
            checks=checks,
        )

    def _verify_pdf_signature(self, file_bytes: bytes) -> Tuple[bool, str, Dict[str, Any]]:
        checks: Dict[str, Any] = {"signature_present": False}
        try:
            from pyhanko.pdf_utils.reader import PdfFileReader
            from pyhanko.sign.validation import validate_pdf_signature

            reader = PdfFileReader(io.BytesIO(file_bytes))
            sigs = reader.embedded_signatures
            if not sigs:
                return False, "No signatures found", checks

            checks["signature_present"] = True
            val = validate_pdf_signature(sigs[0])
            checks["intact"] = val.intact
            checks["valid"] = val.valid
            if val.intact and val.valid:
                return True, "Valid signature", checks
            return False, "Invalid signature", checks
        except Exception as e:
            return False, str(e), checks
